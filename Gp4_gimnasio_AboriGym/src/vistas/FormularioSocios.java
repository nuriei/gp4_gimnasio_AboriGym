    private void jButtonGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonGuardarActionPerformed
        try {
            String dni = jTextFieldDni.getText();
            String nombre = jTextFieldNombre.getText();
            String apellido = jTextFieldApellido.getText();
            int edad = Integer.parseInt(jTextFieldEdad.getText()); // Convierte el texto a número
            String correo = jTextFieldCorreo.getText();
            String telefono = jTextFieldTelefono.getText();
            boolean estado = true;
            
            
            
            Socio nuevoSocio = new Socio(dni, nombre, apellido, edad, correo, telefono, estado);
            
            String url = "jdbc:mysql://localhost:3306/gp4_gimnasio_aborigym";
            MiConexion conexion = new MiConexion(url, "root", "");
            
            SocioData socioData = new SocioData(conexion);
            socioData.guardarSocio(nuevoSocio);
            
            javax.swing.JOptionPane.showMessageDialog(this, "Socio registrado con exito");
            limpiarCampos();
            
            
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, ingresa una edad valida (numero entero).", "Error de formato", javax.swing.JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al guardar el socio: " + e.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
        
        
    }//GEN-LAST:event_jButtonGuardarActionPerformed

